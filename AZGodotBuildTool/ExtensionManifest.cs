using System.Security.Cryptography;
using System.Text.Json;

namespace AZGodotBuildTool;

internal static class ExtensionManifest
{
    private const string Signature = "; Generated by AZGodotBuildTool";
    private static bool IsGenerated(string? header) => header is Signature or "; Generated by azbuild";

    public static void CheckDestinations(List<NativeLibrary> libraries)
    {
        foreach (var library in libraries)
        {
            if (File.Exists(library.Manifest) && !IsGenerated(File.ReadLines(library.Manifest).FirstOrDefault()))
                throw new InvalidOperationException($"Existing descriptor is not owned by AZGodotBuildTool: {library.Manifest}");
        }
    }

    public static void Deploy(GodotProject project, List<NativeLibrary> libraries, BuildTarget target)
    {
        foreach (var library in libraries)
        {
            var folder = Path.Combine(library.Destination, library.BinaryFolder(target));
            var binary = Path.Combine(folder, library.BinaryName(target));
            Directory.CreateDirectory(folder);
            var runtime = new Dictionary<string, string>();
            foreach (string source in library.Modules.SelectMany(m => m.Rules.RuntimeDependencies.Select(m.ResolvePath)).Distinct())
            {
                string destination = Path.Combine(folder, Path.GetFileName(source));
                InstallBinary(source, destination);
                runtime["res://" + Path.GetRelativePath(project.Root, destination).Replace('\\', '/')] =
                    target.Platform == DesktopPlatform.MacOS ? "Contents/Frameworks" : "";
            }
            InstallBinary(NativeBuilder.StagedBinary(project, library, target), binary);

            string[] previous = File.Exists(library.Manifest) ? File.ReadAllLines(library.Manifest) : [];
            var lines = previous.Contains($"entry_symbol = \"{library.Symbol}\"") ? previous.ToList() : EmptyDescriptor(library);
            lines[0] = Signature;
            SetMapping(lines, "[libraries]", target.Feature, LibraryValue(library, target));
            SetMapping(lines, "[dependencies]", target.Feature, runtime.Count == 0 ? null : JsonSerializer.Serialize(runtime));
            RemoveUnusedDependencies(project, folder, previous, lines);
            NativeBuilder.WriteIfChanged(library.Manifest, string.Join(Environment.NewLine, lines) + Environment.NewLine);
            Console.WriteLine($"Ready: {Path.GetRelativePath(project.Root, library.Manifest)}");
        }
    }

    public static void Clean(GodotProject project, BuildTarget variant)
    {
        // Stage directories identify locally built targets even if the Source module was removed.
        // A distributed addon can carry our manifest signature without having been built locally.
        var stage = NativeBuilder.StageDirectory(project, variant);
        if (!Directory.Exists(stage)) return;
        string suffix = variant.Suffix;
        foreach (string targetDir in Directory.EnumerateDirectories(stage))
        foreach (string output in Directory.EnumerateFiles(targetDir, "*" + suffix))
        {
            var target = Path.GetFileName(targetDir);
            string name = Path.GetFileName(output)[..^suffix.Length];
            if (name.Length == 0 || name is "." or "..") continue;
            CleanMapping(project, new(name, target, Path.Combine(project.Root, "Binaries"), false, []), variant);
            CleanMapping(project, new(name, target, Path.Combine(project.Root, "addons", name), true, []), variant);
        }
    }

    private static void CleanMapping(GodotProject project, NativeLibrary library, BuildTarget target)
    {
        if (!File.Exists(library.Manifest)) return;
        var previous = File.ReadAllLines(library.Manifest);
        var lines = previous.ToList();
        if (!IsGenerated(lines.FirstOrDefault()) || !lines.Contains($"entry_symbol = \"{library.Symbol}\"") ||
            !lines.Contains($"{target.Feature} = {LibraryValue(library, target)}")) return;
        lines[0] = Signature;
        var folder = Path.Combine(library.Destination, library.BinaryFolder(target));
        File.Delete(Path.Combine(folder, library.BinaryName(target)));
        SetMapping(lines, "[libraries]", target.Feature, null);
        SetMapping(lines, "[dependencies]", target.Feature, null);
        RemoveUnusedDependencies(project, folder, previous, lines);
        if (lines.SequenceEqual(EmptyDescriptor(library))) File.Delete(library.Manifest);
        else NativeBuilder.WriteIfChanged(library.Manifest, string.Join(Environment.NewLine, lines) + Environment.NewLine);
    }

    private static string LibraryValue(NativeLibrary library, BuildTarget target) =>
        $"\"./{library.BinaryFolder(target)}/{library.BinaryName(target)}\"";

    private static List<string> EmptyDescriptor(NativeLibrary library) =>
        [Signature, "[configuration]", $"entry_symbol = \"{library.Symbol}\"",
         $"compatibility_minimum = \"{GodotProject.ApiVersion}\"", "", "[libraries]"];

    private static void SetMapping(List<string> lines, string section, string key, string? value)
    {
        int start = lines.IndexOf(section);
        if (start < 0)
        {
            if (value is null) return;
            lines.Add("");
            lines.Add(section);
            start = lines.Count - 1;
        }
        int end = lines.FindIndex(start + 1, l => l.StartsWith('['));
        if (end < 0) end = lines.Count;
        while (end > start + 1 && lines[end - 1] == "") end--;
        string prefix = key + " = ";
        int pos = lines.FindIndex(start + 1, end - start - 1, l => l.StartsWith(prefix, StringComparison.Ordinal));
        if (value is not null)
        {
            if (pos >= 0) lines[pos] = prefix + value;
            else lines.Insert(end, prefix + value);
        }
        else if (pos >= 0)
        {
            lines.RemoveAt(pos);
            if (section == "[dependencies]" && end == start + 2)
            {
                lines.RemoveAt(start);
                if (start > 0 && lines[start - 1] == "") lines.RemoveAt(start - 1);
            }
        }
    }

    private static IEnumerable<string> DependencyFiles(IEnumerable<string> lines)
    {
        foreach (var line in lines.SkipWhile(l => l != "[dependencies]").Skip(1).TakeWhile(l => !l.StartsWith('[')))
        {
            int dict = line.IndexOf(" = {", StringComparison.Ordinal);
            if (dict < 0 || !line.EndsWith('}')) continue;
            var values = JsonSerializer.Deserialize<Dictionary<string, string>>(line[(dict + 3)..])!;
            foreach (string file in values.Keys) yield return file;
        }
    }

    private static void RemoveUnusedDependencies(GodotProject project, string folder,
        IEnumerable<string> previous, IEnumerable<string> remaining)
    {
        string prefix = "res://" + Path.GetRelativePath(project.Root, folder).Replace('\\', '/') + "/";
        foreach (string file in DependencyFiles(previous).Except(DependencyFiles(remaining),
                     OperatingSystem.IsWindows() ? StringComparer.OrdinalIgnoreCase : StringComparer.Ordinal))
        {
            string name = Path.GetFileName(file);
            if (file == prefix + name) File.Delete(Path.Combine(folder, name));
        }
    }

    private static void InstallBinary(string source, string destination)
    {
        if (File.Exists(destination) && new FileInfo(source).Length == new FileInfo(destination).Length)
        {
            using var from = File.OpenRead(source);
            using var to = File.OpenRead(destination);
            if (SHA256.HashData(from).AsSpan().SequenceEqual(SHA256.HashData(to))) return;
        }
        var temporary = destination + "." + Guid.NewGuid().ToString("N") + ".tmp";
        try
        {
            File.Copy(source, temporary);
            File.Move(temporary, destination, true);
        }
        finally { File.Delete(temporary); }
    }
}
