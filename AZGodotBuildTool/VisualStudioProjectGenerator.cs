using System.Security.Cryptography;
using System.Text;
using System.Xml.Linq;

namespace AZGodotBuildTool;

internal static class VisualStudioProjectGenerator
{
    private static readonly XNamespace Ms = "http://schemas.microsoft.com/developer/msbuild/2003";
    private static readonly string[] Configs = ["Debug", "Release"];
    private const string Signature = "Generated by AZGodotBuildTool";
    private const string CppProjectType = "{BC8A1FFA-BEE3-4634-8014-F334798102B3}";
    private const string SolutionFolderType = "{2150E333-8FDC-42A3-9474-1A3956D46DE8}";

    private sealed record IndexModel(string Build, Dictionary<NativeModule, string> ModuleIncludes);

    public static void Generate(GodotProject project, List<NativeLibrary> libraries, string? bindings, BuildTarget target)
    {
        var name = Path.GetFileName(project.Root);
        var solution = Path.Combine(project.Root, name + ".AZGodotBuildTool.sln");
        var folder = Path.Combine(project.BuildDirectory, "ide");
        // An empty project can generate its solution before the first source file exists.
        var projects = libraries.Count > 0 ? libraries : [NativeLibrary.FromDirectory(project.Root, false)];
        var files = new Dictionary<string, string> { [solution] = Solution(projects) };
        var models = new Dictionary<string, IndexModel>();
        if (bindings is not null)
            foreach (var config in Configs)
            {
                var variant = target with { Configuration = config };
                foreach (var library in libraries) ModuleRulesLoader.Load(project, library, variant);
                var build = NativeBuilder.PrepareIde(project, libraries, bindings, variant);
                models.Add(config, new(build, libraries.SelectMany(l => l.Modules)
                    .ToDictionary(m => m, m => string.Join(';', m.IncludeDirectories))));
            }

        string invocation = ToolCommand(project);
        foreach (var library in projects)
        {
            var path = Path.Combine(folder, ProjectFileName(library));
            var directory = Path.GetDirectoryName(path)!;
            var items = new List<(string Kind, string Path, NativeModule Module)>();
            foreach (var module in library.Modules)
            {
                items.AddRange(module.Headers.Select(f => ("ClInclude", f, module)));
                items.AddRange(module.Sources.Select(f => ("ClCompile", f, module)));
                if (File.Exists(module.RulesFile)) items.Add(("None", module.RulesFile, module));
            }
            files.Add(path, ProjectFile(library, directory, invocation, models, items));
            files.Add(path + ".filters", Filters(project.Root, directory, items));
        }
        foreach (var path in files.Keys)
        {
            string marker = path == solution ? "# " + Signature : $"<!--{Signature}-->";
            string previousMarker = path == solution ? "# Generated by azbuild" : "<!--Generated by azbuild-->";
            if (File.Exists(path) && !File.ReadLines(path).Take(5).Any(line => line == marker || line == previousMarker))
                throw new InvalidOperationException($"Existing IDE file is not owned by AZGodotBuildTool: {path}");
        }
        foreach (var (path, content) in files) NativeBuilder.WriteIfChanged(path, content);
        Console.WriteLine($"Solution: {solution}");
    }

    private static string ProjectFileName(NativeLibrary library) =>
        Path.Combine(library.IsAddon ? "addon" : "", library.Name + ".vcxproj");

    private static string ToolCommand(GodotProject project)
    {
        var tool = project.ToolPath ?? Environment.ProcessPath
            ?? throw new InvalidOperationException("Cannot locate the AZGodotBuildTool executable.");
        if (!File.Exists(tool)) throw new InvalidOperationException($"AZGodotBuildTool tool not found: {tool}");
        if (Path.GetExtension(tool).Equals(".dll", StringComparison.OrdinalIgnoreCase))
            return $"dotnet \"{tool}\"";
        if (project.ToolPath is null && Path.GetFileNameWithoutExtension(tool).Equals("dotnet", StringComparison.OrdinalIgnoreCase))
            return $"\"{tool}\" \"{typeof(Program).Assembly.Location}\"";
        return $"\"{tool}\"";
    }

    private static string ProjectFile(NativeLibrary library, string folder, string invocation,
        Dictionary<string, IndexModel> models, List<(string Kind, string Path, NativeModule Module)> items)
    {
        var root = new XElement(Ms + "Project", new XAttribute("DefaultTargets", "Build"),
            new XElement(Ms + "ItemGroup", new XAttribute("Label", "ProjectConfigurations"),
                Configs.Select(c => new XElement(Ms + "ProjectConfiguration", new XAttribute("Include", c + "|x64"),
                    Property("Configuration", c), Property("Platform", "x64")))),
            new XElement(Ms + "PropertyGroup", new XAttribute("Label", "Globals"),
                Property("ProjectGuid", Id(library.Target)), Property("Keyword", "MakeFileProj"),
                Property("DisableFastUpToDateCheck", "true")),
            Import("Microsoft.Cpp.Default.props"));
        foreach (var config in Configs)
        {
            var settings = new XElement(Ms + "PropertyGroup", Condition(config), new XAttribute("Label", "Configuration"),
                Property("ConfigurationType", "Makefile"));
            if (models.TryGetValue(config, out var model))
            {
                string indexFile = Path.Combine(model.Build, $"{library.Target}-{config}.index");
                string[] index = File.ReadAllLines(indexFile);
                if (index.Length != 4)
                    throw new InvalidOperationException($"Invalid CMake index settings in '{indexFile}'.");
                settings.Add(Property("PlatformToolset", index[0]), Property("WindowsTargetPlatformVersion", index[1]));
                settings.Add(Property("NMakeIncludeSearchPath", index[2]));
                settings.Add(Property("NMakePreprocessorDefinitions",
                    $"WIN32;_WINDOWS;{(config == "Debug" ? "_DEBUG" : "NDEBUG")};{index[3]}"));
            }
            root.Add(settings);
        }
        root.Add(Import("Microsoft.Cpp.props"));
        foreach (var config in Configs)
        {
            var suffix = " --config " + config.ToLowerInvariant();
            root.Add(new XElement(Ms + "PropertyGroup", Condition(config),
                Property("IntDir", @"$(ProjectDir)obj\$(MSBuildProjectName)\$(Configuration)\"),
                Property("OutDir", @"$(ProjectDir)out\$(Configuration)\"),
                Property("NMakeBuildCommandLine", invocation + " build" + suffix),
                Property("NMakeReBuildCommandLine", invocation + " rebuild" + suffix),
                Property("NMakeCleanCommandLine", invocation + " clean" + suffix),
                // The source set is discovered by AZGodotBuildTool, including files unknown to the IDE.
                Property("NMakeOutput", @"$(IntDir)AZGodotBuildTool-always-invoke"),
                Property("AdditionalOptions", "/std:c++17 /Zc:__cplusplus /utf-8 $(AdditionalOptions)")));
        }
        var sources = new XElement(Ms + "ItemGroup");
        foreach (var (kind, path, module) in items)
        {
            var item = Item(kind, folder, path);
            if (kind != "None")
                foreach (var (config, model) in models)
                    item.Add(new XElement(Ms + "AdditionalIncludeDirectories", Condition(config),
                        model.ModuleIncludes[module] + ";%(AdditionalIncludeDirectories)"));
            sources.Add(item);
        }
        root.Add(sources, Import("Microsoft.Cpp.targets"));
        return Xml(root);
    }

    private static string Filters(string project, string folder, List<(string Kind, string Path, NativeModule Module)> items)
    {
        var groups = new SortedSet<string>(StringComparer.OrdinalIgnoreCase);
        var entries = new XElement(Ms + "ItemGroup");
        foreach (var (kind, path, _) in items)
        {
            var directory = Path.GetDirectoryName(Path.GetRelativePath(project, path));
            var entry = Item(kind, folder, path);
            if (!string.IsNullOrEmpty(directory)) entry.Add(Property("Filter", directory));
            entries.Add(entry);
            for (var parent = directory; !string.IsNullOrEmpty(parent); parent = Path.GetDirectoryName(parent))
                groups.Add(parent);
        }
        return Xml(new XElement(Ms + "Project", new XElement(Ms + "ItemGroup",
            groups.Select(g => new XElement(Ms + "Filter", new XAttribute("Include", g),
                Property("UniqueIdentifier", Id(g))))), entries));
    }

    private static string Solution(List<NativeLibrary> projects)
    {
        var text = new StringBuilder();
        text.AppendLine("Microsoft Visual Studio Solution File, Format Version 12.00");
        text.AppendLine("# Visual Studio Version 17");
        text.AppendLine("# " + Signature);
        var addons = projects.Where(l => l.IsAddon).ToArray();
        var addonFolderId = Id("solution-folder/addon");
        if (addons.Length > 0)
        {
            text.AppendLine($"Project(\"{SolutionFolderType}\") = \"addon\", \"addon\", \"{addonFolderId}\"");
            text.AppendLine("EndProject");
        }
        foreach (var library in projects)
        {
            text.AppendLine($"Project(\"{CppProjectType}\") = \"{library.Name}\", \".build\\ide\\{ProjectFileName(library)}\", \"{Id(library.Target)}\"");
            text.AppendLine("EndProject");
        }
        text.AppendLine("Global");
        text.AppendLine("\tGlobalSection(SolutionConfigurationPlatforms) = preSolution");
        foreach (var c in Configs) text.AppendLine($"\t\t{c}|x64 = {c}|x64");
        text.AppendLine("\tEndGlobalSection");
        text.AppendLine("\tGlobalSection(ProjectConfigurationPlatforms) = postSolution");
        foreach (var library in projects)
        foreach (var c in Configs)
        {
            var key = $"{Id(library.Target)}.{c}|x64";
            text.AppendLine($"\t\t{key}.ActiveCfg = {c}|x64");
            // Each project has its own index settings, but the solution dispatches once.
            if (library == projects[0]) text.AppendLine($"\t\t{key}.Build.0 = {c}|x64");
        }
        text.AppendLine("\tEndGlobalSection");
        if (addons.Length > 0)
        {
            text.AppendLine("\tGlobalSection(NestedProjects) = preSolution");
            foreach (var addon in addons) text.AppendLine($"\t\t{Id(addon.Target)} = {addonFolderId}");
            text.AppendLine("\tEndGlobalSection");
        }
        text.AppendLine("EndGlobal");
        return text.ToString();
    }

    // Keep existing solution project and filter GUIDs across the tool rename.
    private static string Id(string name) =>
        new Guid(SHA256.HashData(Encoding.UTF8.GetBytes("azbuild:" + name)).AsSpan(0, 16)).ToString("B").ToUpperInvariant();
    private static XElement Property(string name, string value) => new(Ms + name, value);
    private static XElement Import(string file) => new(Ms + "Import", new XAttribute("Project", @"$(VCTargetsPath)\" + file));
    private static XAttribute Condition(string config) => new("Condition", $"'$(Configuration)|$(Platform)'=='{config}|x64'");
    private static XElement Item(string kind, string folder, string file) =>
        new(Ms + kind, new XAttribute("Include", Path.GetRelativePath(folder, file)));
    private static string Xml(XElement root) => new XDocument(new XComment(Signature), root) + Environment.NewLine;
}
